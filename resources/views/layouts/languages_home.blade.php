<script>
    document.addEventListener('DOMContentLoaded', function() {
        const openPopupBtn = document.getElementById('openPopup');
        if (openPopupBtn) {
            openPopupBtn.addEventListener('click', function(e) {
                e.preventDefault();
                openLanguageModal();
            });
        }
    });

    function openLanguageModal() {
        const desktopList = document.querySelector('#language-dropdown-menu ul');
        const mobileListContainer = document.getElementById('mobileLanguageList');
        
        if (desktopList && mobileListContainer && mobileListContainer.children.length === 0) {
            mobileListContainer.innerHTML = desktopList.innerHTML;
             const items = mobileListContainer.querySelectorAll('li');
             items.forEach(item => {
                 item.style.borderBottom = '1px solid #eee';
                 // Ensure links work
                 const link = item.querySelector('a');
                 if(link) {
                     link.classList.add('w-full', 'justify-between');
                 }
             });
        }
        document.getElementById('languageModalMobile').classList.remove('hidden');
    }

    function closeLanguageModal() {
        document.getElementById('languageModalMobile').classList.add('hidden');
    }
</script>

               